"""Build audio/voice_sfx.wav: the aligned narration + the ElevenLabs sound effects, placed on the
film's timeline (times match js/core.js). Also writes js/voice-data.js so the synthesised music
ducks under the narrator.

usage: python3 tools/mix_voice_sfx.py
"""
import json, subprocess, wave
import numpy as np

SR, DUR = 44100, 78.7
D = 'audio/sfx/'

def load(path, af=None):
    cmd = ['ffmpeg', '-v', 'error', '-i', path] + (['-af', af] if af else []) + ['-ac', '1', '-ar', str(SR), '-f', 'f32le', '-']
    x = np.frombuffer(subprocess.run(cmd, capture_output=True, check=True).stdout, dtype=np.float32).copy()
    return x

def norm(x, peak_db):
    p = np.abs(x).max()
    return x if p < 1e-6 else x * (10 ** (peak_db / 20) / p)

sfx = np.zeros(int(DUR * SR) + SR * 4, dtype=np.float32)
def place(x, t, gain_db=0.0, length=None, fade_out=0.08):
    if length: x = x[:int(length * SR)].copy()
    f = min(len(x) // 2, int(fade_out * SR))
    if f > 0: x[-f:] *= np.linspace(1, 0, f)
    s = int(t * SR)
    sfx[s:s + len(x)] += x * 10 ** (gain_db / 20)

# --- one-shots (times from js/core.js) ---
place(norm(load(D + 'knife.mp3'), -6), 0.25)
place(norm(load(D + 'scream.mp3', 'lowpass=f=1800,highpass=f=300'), -10), 16.75)        # through the glass
place(norm(load(D + 'mug.mp3'), -3), 23.98)
place(norm(load(D + 'alt/switch_2.mp3'), -4), 29.15)
place(norm(load(D + 'curtains.mp3'), -6), 33.6)
md = norm(load(D + 'alt/maindoor_2.mp3', 'lowpass=f=2500,aecho=0.8:0.6:120:0.35'), -6)
for t, g in [(41.0, 0), (41.35, -2), (41.7, -1)]: place(md, t, g, length=0.9)
fs = [norm(load(D + n, 'highpass=f=80'), -9) for n in ['footsteps.mp3', 'alt/footsteps_2.mp3', 'alt/footsteps_3.mp3', 'alt/footsteps_4.mp3']]
for i, t in enumerate(np.arange(41.7, 45.0, 0.95)): place(fs[i % 4], t, -8 + i * 2.2, length=1.0)
place(norm(load(D + 'knock.mp3'), -6), 44.95, length=1.9, fade_out=0.3)
pounds = [norm(load(D + n), -2) for n in ['pound.mp3', 'alt/pound_2.mp3', 'alt/pound_3.mp3', 'alt/pound_4.mp3']]
blows = [48.4, 49.05, 49.7, 50.3, 50.95, 51.6, 52.25, 52.9, 53.55, 54.2]
for i, t in enumerate(blows): place(pounds[i % 4], t - 0.03, -1 if i < 8 else 0, length=0.9, fade_out=0.25)
place(norm(load(D + 'crack.mp3'), -2), 53.62)
place(norm(load(D + 'burst.mp3'), -1), 72.3, fade_out=0.3)
place(norm(load(D + 'burst.mp3', 'lowpass=f=900'), -6), 72.45)
gl = norm(load(D + 'glitch.mp3'), -7)
for t in [21.0, 53.67, 77.0]: place(gl, t, length=0.45)
place(norm(load(D + 'sting.mp3'), -3), 77.0, fade_out=0.4)

# --- freezing wind bed: chain the 4 wind takes with crossfades from the window opening ---
winds = [norm(load(D + n), -10) for n in ['wind.mp3', 'alt/wind_2.mp3', 'alt/wind_3.mp3', 'alt/wind_4.mp3']]
t, i, xf = 59.2, 0, 0.35
env_pts = [(59.2, -4), (61, -6), (66, -9), (71, -8), (71.05, -16), (72.3, -16), (74, -7), (75.2, -40)]
def env_db(tt): return np.interp(tt, [p[0] for p in env_pts], [p[1] for p in env_pts])
while t < 75.2:
    w = winds[i % 4].copy(); n = len(w); f = int(xf * SR)
    w[:f] *= np.linspace(0, 1, f); w[-f:] *= np.linspace(1, 0, f)
    place(w, t, env_db(t), fade_out=0)
    t += n / SR - xf; i += 1

# --- narration ---
# broadcast-style voice chain: gentle compression + presence so the narrator sits on top of the score
voice = load('audio/narration.wav', 'highpass=f=70,equalizer=f=3000:t=q:w=1.2:g=2.5,acompressor=threshold=-30dB:ratio=6:attack=4:release=120:makeup=14dB,alimiter=limit=0.89:level=false')
out = sfx[:int(DUR * SR)] * 0.8
out[:len(voice)] += voice[:len(out)]
peak = np.abs(out).max()
if peak > 0.97: out *= 0.97 / peak
with wave.open('audio/voice_sfx.wav', 'wb') as w:
    w.setnchannels(1); w.setsampwidth(2); w.setframerate(SR)
    w.writeframes((out * 32767).astype(np.int16).tobytes())

# narration segments for ducking the music
v = np.abs(load('audio/narration.wav')); win = int(0.05 * SR)
on = np.convolve(v, np.ones(win) / win, mode='same') > 0.02
segs, s = [], None
for k in range(0, len(on), win):
    if on[k] and s is None: s = k / SR
    if not on[k] and s is not None:
        segs.append([round(s, 2), round(k / SR, 2)]); s = None
merged = []
for a, b in segs:
    if merged and a - merged[-1][1] < 0.35: merged[-1][1] = b
    else: merged.append([a, b])
open('js/voice-data.js', 'w').write('/* generated by tools/mix_voice_sfx.py: when the narrator is speaking (music ducks) */\n'
                                    'window.VOICE = { file: "audio/voice_sfx.mp3", segments: ' + json.dumps(merged) + ' };\n')
print('segments', len(merged), 'peak', round(float(peak), 3))
