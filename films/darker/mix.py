"""Darker: narration + recorded ElevenLabs effects on the film's timeline -> films/darker/audio/voice_sfx.wav/.mp3
and films/darker/voice-data.js. The cue times come from films/darker/core.js (evaluated with node), so the
sounds land on the same frames as the picture.
usage: python3 films/darker/mix.py   (after prep_narration.py)
"""
import json, subprocess, wave
import numpy as np

SR = 44100
B = 'films/darker/'
NODE = """
global.window = global;
require('./js/core.js'); require('./films/darker/words.js'); require('./films/darker/core.js');
const T = window.TL;
console.log(JSON.stringify({ lamps: T.lamps, creature: T.creature, cut: T.CUT, close: T.close, D: T.D, dur: T.DURATION, sents: window.DK_SENTENCES }));
"""
C = json.loads(subprocess.run(['node', '-e', NODE], capture_output=True, check=True, text=True).stdout)
DUR = C['dur']

def load(path, af=None):
    cmd = ['ffmpeg', '-v', 'error', '-i', path] + (['-af', af] if af else []) + ['-ac', '1', '-ar', str(SR), '-f', 'f32le', '-']
    return np.frombuffer(subprocess.run(cmd, capture_output=True, check=True).stdout, dtype=np.float32).copy()
def rms_norm(x, db):
    r = np.sqrt(np.mean(x ** 2)); return x if r < 1e-9 else x * (10 ** (db / 20) / r)
sfx = np.zeros(int((DUR + 5) * SR), dtype=np.float32)
def place(x, t, gain_db=0.0, fade_in=0.01, fade_out=0.05):
    x = x.copy()
    fi, fo = min(len(x) // 2, int(fade_in * SR)), min(len(x) // 2, int(fade_out * SR))
    if fi: x[:fi] *= np.linspace(0, 1, fi)
    if fo: x[-fo:] *= np.linspace(1, 0, fo)
    s = int(t * SR); sfx[s:s + len(x)] += x[:len(sfx) - s] * 10 ** (gain_db / 20)
D = B + 'audio/sfx/'

# crickets from dusk until "Something moves between the trees" -- then they stop dead
cr = [rms_norm(load(D + 'crickets_3.mp3'), -30), rms_norm(load(D + 'crickets_1.mp3'), -30)]
t0, t1 = C['D']['dusk'] - 1.2, C['creature']['t0'] + 0.05
t, i = t0, 0
while t < t1:
    w = cr[i % 2]; place(w[:int(min(len(w), (t1 - t) * SR))], t, -3 + min(0, (t - t0) * 3 - 12), fade_in=0.12, fade_out=0.12)
    t += len(w) / SR - 0.12; i += 1

# the streetlights: a crackle as each one stutters on, and each dies with the recorded pop
on_crackle = load(D + 'lamp_1.mp3', 'highpass=f=800')
for k, L in enumerate(C['lamps']):
    place(rms_norm(on_crackle[int(0.2 * SR):int(0.9 * SR)], -24), L['on'], -2 * k, fade_out=0.15)
die = [load(D + 'lamp_4.mp3', 'highpass=f=500'), load(D + 'lamp_2.mp3', 'highpass=f=500')]
for k, L in enumerate(C['lamps']):     # index 0 is the nearest lamp (loudest); the far one dies first
    clip = die[k % 2]
    end = len(clip) if k % 2 == 0 else int(2.75 * SR)
    seg = clip[max(0, end - int(0.8 * SR)):end]
    place(rms_norm(seg, -20), L['off'] - len(seg) / SR + 0.03, -3 * k, fade_in=0.2, fade_out=0.02)

# the close-up: a heavy breath right in front of you, then a lower one on "see"
cl = C['close']
place(rms_norm(load(D + 'breath_3.mp3', 'lowpass=f=3000'), -18), cl['t0'] + 0.05, 0, fade_out=0.15)
place(rms_norm(load(D + 'breath_2.mp3', 'lowpass=f=1800,asetrate=44100*0.85,aresample=44100'), -19), cl['see'] + 0.15, 0, fade_out=0.2)

cut = int(C['cut'] * SR); sfx[cut:] = 0          # nothing recorded survives the cut to black
voice = load(B + 'audio/voice.wav')
out = sfx[:int(DUR * SR)]
out[:min(len(voice), len(out))] += voice[:len(out)]
peak = np.abs(out).max()
if peak > 0.97: out *= 0.97 / peak
with wave.open(B + 'audio/voice_sfx.wav', 'wb') as w:
    w.setnchannels(1); w.setsampwidth(2); w.setframerate(SR); w.writeframes((np.clip(out, -1, 1) * 32767).astype(np.int16).tobytes())
subprocess.run(['ffmpeg', '-v', 'error', '-y', '-i', B + 'audio/voice_sfx.wav', '-b:a', '160k', B + 'audio/voice_sfx.mp3'], check=True)
merged = []
for a, b, _ in C['sents']:
    if merged and a - merged[-1][1] < 0.35: merged[-1][1] = b
    else: merged.append([a, b])
open(B + 'voice-data.js', 'w').write('/* generated by films/darker/mix.py */\nwindow.VOICE = { file: "films/darker/audio/voice_sfx.mp3", wav: "films/darker/audio/voice_sfx.wav", segments: '
                                     + json.dumps([[round(a, 2), round(b, 2)] for a, b in merged]) + ' };\n')
print('ok, peak', round(float(peak), 3))
