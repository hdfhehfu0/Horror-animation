"""Rogue planet (POV): cut the two voice takes into lines and place each line on the film timeline.

The friend (deep voice, "Brian"; white captions) and the hero (the POV, "Lip"; #FFD54A captions) were generated
as one take each. Each take is split at its pauses; pieces that belong to one line are joined (GROUPS), and every
line is set where its scene plays (start times below). The hero's "Subhan Allah" stays Arabic in the sound with an
accurate English caption (pronunciation review pending).

Writes films/planet/lines.js, films/planet/audio/voice.wav/.mp3 and films/planet/voice-data.js.
usage: python3 films/planet/prep_voices.py
"""
import json, subprocess, wave
import numpy as np

SR = 44100
B = 'films/planet/'
DUR = 66.5
FRIEND = [  # (start, caption, pieces of the take that make the line)
    (2.8, 'In five seconds, a rogue planet the size of Saturn passes as close as the Moon.', [0, 1]),
    (10.6, "A planet with no sun. It may have been drifting between the stars for billions of years.", [2, 3]),
    (17.0, "At the Moon's distance, it looks more than 30 times wider than the Moon.", [4]),
    (24.2, 'Its rings would stretch across 75 full Moons of sky.', [5]),
    (29.0, "Now feel its pull. It's nearly 8,000 times heavier than the Moon.", [6, 7]),
    (37.2, 'The Moon lifts the oceans about half a meter. This could lift them kilometers high.', [8, 9]),
    (49.2, 'Here it comes.', [10]),
    (58.0, "We'd never see one coming. Rogue planets don't shine, until a sun lights them up.", [11, 12, 13]),
]
HERO = [  # (start, caption, pieces, loudness dBFS RMS)
    (8.7, 'What is that?', [0], -21),
    (21.8, 'Those are its rings...', [1], -23),
    (34.0, "The water... it's going out.", [2, 3], -21),
    (46.0, 'Glory be to God.', [4], -22),          # spoken: "Subhan Allah"
]

def load(path):
    return np.frombuffer(subprocess.run(['ffmpeg', '-v', 'error', '-i', path, '-ac', '1', '-ar', str(SR), '-f', 'f32le', '-'],
                                        capture_output=True, check=True).stdout, dtype=np.float32).copy()
def split(x, thr_db, min_gap=0.28, min_len=0.15):
    w = int(0.02 * SR); e = np.array([np.sqrt(np.mean(x[i:i + w] ** 2)) for i in range(0, len(x) - w, w)])
    on = 20 * np.log10(e + 1e-9) > thr_db; out, i, n = [], 0, len(on)
    while i < n:
        if not on[i]: i += 1; continue
        j = i
        while j < n:
            if on[j]: j += 1; continue
            k = j
            while k < n and not on[k]: k += 1
            if k - j >= min_gap / 0.02 or k == n: break
            j = k
        if (j - i) * 0.02 > min_len: out.append([max(0, i * 0.02 - 0.06), min(len(x) / SR, j * 0.02 + 0.12)])
        i = j
    return out

friend, hero = load(B + 'audio/raw/friend_a.mp3'), load(B + 'audio/raw/hero_a.mp3')
fs, hs = split(friend, -42), split(hero, -46)
assert len(fs) == 14 and len(hs) == 5, (len(fs), len(hs))
film = np.zeros(int(DUR * SR), dtype=np.float32)
rms = lambda a: np.sqrt(np.mean(a ** 2)) + 1e-9
def put(seg, t, gain):
    seg = seg.copy(); f = int(0.015 * SR); seg[:f] *= np.linspace(0, 1, f); seg[-f:] *= np.linspace(1, 0, f)
    s = int(t * SR); film[s:s + len(seg)] += seg[:len(film) - s] * gain
lines = []
fg = 10 ** (-19 / 20) / rms(np.concatenate([friend[int(a * SR):int(b * SR)] for a, b in fs]))
for t, text, ps in FRIEND:
    a, b = fs[ps[0]][0], fs[ps[-1]][1]; put(friend[int(a * SR):int(b * SR)], t, fg); lines.append([round(t, 3), round(t + b - a, 3), 'friend', text])
for t, text, ps, db in HERO:
    a, b = hs[ps[0]][0], hs[ps[-1]][1]; seg = hero[int(a * SR):int(b * SR)]; put(seg, t, 10 ** (db / 20) / rms(seg)); lines.append([round(t, 3), round(t + b - a, 3), 'hero', text])
lines.sort()
for i in range(len(lines) - 1): assert lines[i][1] < lines[i + 1][0] + 0.05, lines[i:i + 2]
film = np.clip(film, -0.98, 0.98)
with wave.open(B + 'audio/narration.wav', 'wb') as w:
    w.setnchannels(1); w.setsampwidth(2); w.setframerate(SR); w.writeframes((film * 32767).astype(np.int16).tobytes())
subprocess.run(['ffmpeg', '-v', 'error', '-y', '-i', B + 'audio/narration.wav', '-af',
                'highpass=f=55,equalizer=f=3000:t=q:w=1.2:g=1.5,acompressor=threshold=-24dB:ratio=2.5:attack=5:release=150:makeup=3dB,alimiter=limit=0.89:level=false',
                B + 'audio/voice.wav'], check=True)
open(B + 'lines.js', 'w').write('/* generated by films/planet/prep_voices.py: [start, end, voice, caption] */\n'
                                f'window.PL_DURATION = {DUR};\nwindow.PL_LINES = ' + json.dumps(lines, indent=0, ensure_ascii=False) + ';\n')
for l in lines: print(f'{l[0]:6.2f}-{l[1]:6.2f} {l[2]:6s} {l[3]}')
