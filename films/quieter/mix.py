"""Quieter: narration + recorded ElevenLabs effects on the film's timeline -> films/quieter/audio/voice_sfx.wav/.mp3
and films/quieter/voice-data.js. Cue times come from films/quieter/core.js (evaluated with node), so every sound
stops on the same frame as the thing that makes it.
usage: python3 films/quieter/mix.py   (after prep_narration.py)
"""
import json, subprocess, wave
import numpy as np

SR = 44100
B = 'films/quieter/'
NODE = """
global.window = global;
require('./js/core.js'); require('./films/quieter/words.js'); require('./films/quieter/core.js');
const T = window.TL;
console.log(JSON.stringify({ Q: T.Q, cars: T.cars, carTime: T.carTime, cut: T.CUT, dur: T.DURATION, sents: window.QT_SENTENCES }));
"""
C = json.loads(subprocess.run(['node', '-e', NODE], capture_output=True, check=True, text=True).stdout)
DUR, Q, S = C['dur'], C['Q'], C['sents']

def load(path, af=None):
    cmd = ['ffmpeg', '-v', 'error', '-i', path] + (['-af', af] if af else []) + ['-ac', '1', '-ar', str(SR), '-f', 'f32le', '-']
    return np.frombuffer(subprocess.run(cmd, capture_output=True, check=True).stdout, dtype=np.float32).copy()
def rms_norm(x, db):
    r = np.sqrt(np.mean(x ** 2)); return x if r < 1e-9 else x * (10 ** (db / 20) / r)
sfx = np.zeros(int((DUR + 5) * SR), dtype=np.float32)
def place(x, t, gain_db=0.0, fade_in=0.01, fade_out=0.05):
    x = x.copy()
    fi, fo = min(len(x) // 2, int(fade_in * SR)), min(len(x) // 2, int(fade_out * SR))
    if fi: x[:fi] *= np.linspace(0, 1, fi)
    if fo: x[-fo:] *= np.linspace(1, 0, fo)
    s = int(t * SR); sfx[s:s + len(x)] += x[:len(sfx) - s] * 10 ** (gain_db / 20)
def bed(clip, t0, t1, db, fade_in=0.4, fade_out=0.15, env=None):
    """loop `clip` from t0 to t1 with crossfades; env(t) -> extra gain in dB"""
    t = t0
    while t < t1:
        n = int(min(len(clip), (t1 - t) * SR)); seg = clip[:n].copy()
        if env is not None: seg *= 10 ** (np.array([env(t + i / SR) for i in range(0, n, 441)]).repeat(441)[:n] / 20)
        place(seg, t, db, fade_in=fade_in if t == t0 else 0.25, fade_out=fade_out if t + n / SR >= t1 - 1e-3 else 0.25)
        t += len(clip) / SR - 0.25
D = B + 'audio/sfx/'

# the afternoon (traffic, a lawnmower, kids far off) fades away with "The traffic fades away."
t_tr0, t_tr1 = S[3][0], S[3][1] + 0.6
bed(rms_norm(load(D + 'afternoon_4.mp3'), -24), 0, t_tr1, 0, fade_in=0.05, fade_out=0.6,
    env=lambda t: 0 if t < t_tr0 else -40 * min(1, (t - t_tr0) / (t_tr1 - t_tr0)) ** 1.5)
# cars crossing behind the barricade: the sound peaks as each one passes the gap
cars = [rms_norm(load(D + 'car_3.mp3'), -22), rms_norm(load(D + 'car_4.mp3'), -22)]
for i, (t0, dirn, lane, col) in enumerate(C['cars']):
    mid = t0 + C['carTime'] / 2
    clip = cars[i % 2]; pk = int(np.argmax(np.convolve(clip ** 2, np.ones(4410), 'same')))
    place(clip, mid - pk / SR, -3 - 2 * i if mid < t_tr0 else -16, fade_in=0.3, fade_out=0.5)
# birdsong until "The birds stop singing" -- it stops as they leave the wire
birds = rms_norm(load(D + 'birds_3.mp3'), -26)
bed(birds, 0, Q['birdsOff'] + 0.15, 0, fade_in=0.05, fade_out=0.12)
# wing beats as they take off
flap = load(D + 'wind_2.mp3', 'bandpass=f=900:w=600')[:int(0.6 * SR)]
for k in range(4): place(rms_norm(flap, -30), Q['birdsOff'] + 0.05 + k * 0.12, -k * 2, fade_in=0.01, fade_out=0.3)
# the wind, until "Even the wind goes still" -- it stops dead, like everything it was moving
bed(rms_norm(load(D + 'wind_2.mp3'), -27), 0, Q['still'] + 0.08, 0, fade_in=0.05, fade_out=0.06)
# your own breathing, until you hold it on "Then,"
bed(rms_norm(load(D + 'mybreath_1.mp3', 'highpass=f=80'), -30), Q['breathe0'] - 0.3, Q['breathe1'] + 0.05, 0, fade_in=0.5, fade_out=0.08)
# total silence ... then something breathes, behind you, closer on "right"
place(rms_norm(load(D + 'breath_3.mp3', 'lowpass=f=3500'), -20), Q['breath'] + 0.05, 0, fade_out=0.15)
place(rms_norm(load(D + 'breath_2.mp3', 'lowpass=f=2200,asetrate=44100*0.82,aresample=44100'), -18), Q['right'] + 0.1, 0, fade_out=0.25)

cut = int(C['cut'] * SR); sfx[cut:] = 0
voice = load(B + 'audio/voice.wav')
out = sfx[:int(DUR * SR)]
out[:min(len(voice), len(out))] += voice[:len(out)]
peak = np.abs(out).max()
if peak > 0.97: out *= 0.97 / peak
with wave.open(B + 'audio/voice_sfx.wav', 'wb') as w:
    w.setnchannels(1); w.setsampwidth(2); w.setframerate(SR); w.writeframes((np.clip(out, -1, 1) * 32767).astype(np.int16).tobytes())
subprocess.run(['ffmpeg', '-v', 'error', '-y', '-i', B + 'audio/voice_sfx.wav', '-b:a', '160k', B + 'audio/voice_sfx.mp3'], check=True)
merged = []
for a, b, _ in S:
    if merged and a - merged[-1][1] < 0.35: merged[-1][1] = b
    else: merged.append([a, b])
open(B + 'voice-data.js', 'w').write('/* generated by films/quieter/mix.py */\nwindow.VOICE = { file: "films/quieter/audio/voice_sfx.mp3", wav: "films/quieter/audio/voice_sfx.wav", segments: '
                                     + json.dumps([[round(a, 2), round(b, 2)] for a, b in merged]) + ' };\n')
print('ok, peak', round(float(peak), 3))
