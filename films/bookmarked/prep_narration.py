"""Bookmarked: tighten the narration take and put it on the film's timeline.

The ElevenLabs take is read at a slow, deliberate pace (88 s). This script:
  1. finds every pause (ffmpeg silencedetect),
  2. shortens it (sentence ends keep a little more air than commas),
  3. speeds the voice up slightly with atempo (pitch is unchanged),
  4. maps the per-word times from the ElevenLabs transcript through the same edit.

Writes films/bookmarked/audio/narration.wav and films/bookmarked/words.js (word + sentence timings).
usage: python3 films/bookmarked/prep_narration.py [tempo]
"""
import json, re, subprocess, sys, wave
import numpy as np

SR = 44100
B = 'films/bookmarked/'
SRC = B + 'audio/raw/narr_a.mp3'
WORDS = json.load(open(B + 'audio/raw/narr_a.words.json'))['words']
TEMPO = float(sys.argv[1]) if len(sys.argv) > 1 else 1.08
OFFSET = 0.35          # the first word starts here on the film timeline
OUTRO = 2.6            # end card after the last word

pcm = subprocess.run(['ffmpeg', '-v', 'error', '-i', SRC, '-ac', '1', '-ar', str(SR), '-f', 'f32le', '-'], capture_output=True, check=True).stdout
x = np.frombuffer(pcm, dtype=np.float32).copy()
total = len(x) / SR

log = subprocess.run(['ffmpeg', '-hide_banner', '-i', SRC, '-af', 'silencedetect=noise=-42dB:d=0.09', '-f', 'null', '-'], capture_output=True, text=True).stderr
st = [float(v) for v in re.findall(r'silence_start: ([\d.]+)', log)]
en = [float(v) for v in re.findall(r'silence_end: ([\d.]+)', log)]
sil = list(zip(st, en))
words = [w for w in WORDS if w['type'] == 'word' and not w['text'].startswith('[')]

def ends_sentence(t):
    """Does the word spoken just before time t end a sentence?"""
    prev = [w for w in words if w['start'] < t]
    if not prev: return True
    s = prev[-1]['text'].rstrip('"')
    return s.endswith(('.', '?', '!', ':')) and not s.endswith('...')

# keep-lists of [a, b] in the source; pauses get a new length
pieces = []   # (src_a, src_b, new_len)  new_len == None -> keep as is
cur = 0.0
for a, b in sil:
    if a <= 0.02:            # leading silence: drop
        cur = b; continue
    if b >= total - 0.02:    # trailing silence: drop
        pieces.append((cur, a, None)); cur = None; break
    pieces.append((cur, a, None))
    d = b - a
    if ends_sentence((a + b) / 2): new = min(d, 0.24 + 0.12 * min(1.0, d / 1.2))
    else: new = min(d, 0.08 + 0.10 * min(1.0, d / 0.8))
    pieces.append((a, b, new))
    cur = b
if cur is not None: pieces.append((cur, total, None))

out, mapping, t_out = [], [], 0.0   # mapping: (src_a, src_b, out_a, out_b)
for a, b, new in pieces:
    seg = x[int(a * SR):int(b * SR)]
    if new is not None:   # pause: keep its first and last halves, crossfaded
        n = int(new * SR); h = n // 2
        if n < len(seg):
            seg = np.concatenate([seg[:h], seg[len(seg) - (n - h):]])
    out.append(seg)
    mapping.append((a, b, t_out, t_out + len(seg) / SR))
    t_out += len(seg) / SR
y = np.concatenate(out)

def remap(t):
    for a, b, oa, ob in mapping:
        if a <= t <= b:
            return oa + (ob - oa) * (t - a) / max(1e-9, b - a)
    return mapping[-1][3] if t > mapping[-1][1] else 0.0

r = subprocess.run(['ffmpeg', '-v', 'error', '-f', 'f32le', '-ar', str(SR), '-ac', '1', '-i', '-', '-af', f'atempo={TEMPO}', '-f', 'f32le', '-'],
                   input=y.tobytes(), capture_output=True, check=True)
z = np.frombuffer(r.stdout, dtype=np.float32).copy()
z /= max(1e-6, np.abs(z).max()) / 0.89
place = lambda t: round(OFFSET + remap(t) / TEMPO, 3)

wl = [[place(w['start']), place(w['end']), w['text'].strip('"')] for w in words]
DUR = round(wl[-1][1] + OUTRO, 2)
film = np.zeros(int(DUR * SR), dtype=np.float32)
s0 = int(OFFSET * SR); film[s0:s0 + len(z)] = z[:len(film) - s0]
with wave.open(B + 'audio/narration.wav', 'wb') as w:
    w.setnchannels(1); w.setsampwidth(2); w.setframerate(SR)
    w.writeframes((np.clip(film, -1, 1) * 32767).astype(np.int16).tobytes())

# sentences = runs of words up to . ? ! (a "..." does not end a sentence)
sents, curw = [], []
for w in wl:
    curw.append(w)
    t = w[2]
    if t.endswith(('.', '?', '!')) and not t.endswith('...'):
        sents.append([curw[0][0], curw[-1][1], ' '.join(v[2] for v in curw)]); curw = []
if curw: sents.append([curw[0][0], curw[-1][1], ' '.join(v[2] for v in curw)])

open(B + 'words.js', 'w').write(
    '/* generated by films/bookmarked/prep_narration.py: narration timing on the film timeline */\n'
    f'window.BM_DURATION = {DUR};\n'
    'window.BM_WORDS = ' + json.dumps(wl) + ';\n'
    'window.BM_SENTENCES = ' + json.dumps(sents, indent=0) + ';\n')
json.dump({'duration': DUR, 'tempo': TEMPO, 'words': wl, 'sentences': sents}, open(B + 'audio/narration.timings.json', 'w'), indent=1)

# the voice track the film plays: EQ + compression, then voice-data.js (when the narrator speaks, so the score ducks)
subprocess.run(['ffmpeg', '-v', 'error', '-y', '-i', B + 'audio/narration.wav', '-af',
                'highpass=f=70,equalizer=f=3000:t=q:w=1.2:g=2.5,acompressor=threshold=-28dB:ratio=4:attack=4:release=120:makeup=8dB,loudnorm=I=-16:TP=-2:LRA=7,alimiter=limit=0.89:level=false',
                B + 'audio/voice.wav'], check=True)
subprocess.run(['ffmpeg', '-v', 'error', '-y', '-i', B + 'audio/voice.wav', '-b:a', '160k', B + 'audio/voice.mp3'], check=True)
merged = []
for a, b, _ in sents:
    if merged and a - merged[-1][1] < 0.35: merged[-1][1] = b
    else: merged.append([a, b])
open(B + 'voice-data.js', 'w').write('/* generated by films/bookmarked/prep_narration.py */\nwindow.VOICE = { file: "films/bookmarked/audio/voice.mp3", wav: "films/bookmarked/audio/voice.wav", segments: '
                                     + json.dumps([[round(a, 2), round(b, 2)] for a, b in merged]) + ' };\n')
for i, s in enumerate(sents): print(f'{i:2d} {s[0]:6.2f}-{s[1]:6.2f}  {s[2]}')
print(f'duration {DUR}s, voice {len(z)/SR:.2f}s (tempo x{TEMPO}), {len(wl)} words')
