/* =========================================================================
   BOOKMARKED — core.js
   The timeline. Every shot and cue is placed on the narration's real word
   timings (films/bookmarked/words.js, generated by prep_narration.py), so
   the cuts, the pops, the captions and the voice stay together.
   Requires js/core.js first (it provides U); this replaces window.TL.
   ========================================================================= */
(function (g) {
  'use strict';
  const { U } = g;
  const WORDS = g.BM_WORDS, S = g.BM_SENTENCES, DUR = g.BM_DURATION;
  const at = (i) => S[i][0];
  const end = (i) => S[i][1];
  const cut = (i) => +(S[i][0] - 0.12).toFixed(3);
  const norm = (s) => s.toLowerCase().replace(/[^a-z']/g, '');
  // start of the first word `txt` spoken at or after time t0
  function wa(txt, t0 = 0) {
    const k = norm(txt);
    for (const w of WORDS) if (w[0] >= t0 - 0.02 && norm(w[2]) === k) return w[0];
    throw new Error(`word "${txt}" not found after ${t0}`);
  }

  const TL = {
    W: 1080, H: 1920, FPS: 30, DURATION: DUR,
    TITLE: 'Bookmarked', SLUG: 'bookmarked', POSTER: 3.9,

    /* shots: [start, end, scene, variant] */
    shots: [
      [0, cut(1), 'vs', 'intro'],
      [cut(1), cut(2), 'city'],
      [cut(2), cut(3), 'evidence'],
      [cut(3), cut(4), 'board'],
      [cut(4), cut(7), 'map'],
      [cut(7), cut(8), 'shop'],
      [cut(8), cut(10), 'counter'],
      [cut(10), cut(11), 'shadow'],
      [cut(11), cut(13), 'lean'],
      [cut(13), cut(14), 'backroom'],
      [cut(14), cut(16), 'case'],
      [cut(16), cut(17), 'box'],
      [cut(17), cut(18), 'receipts'],
      [cut(18), cut(19), 'temple'],
      [cut(19), cut(20), 'vs', 'team'],
      [cut(20), cut(22), 'skills'],
      [cut(22), cut(25), 'shelf'],
      [cut(25), cut(26), 'caught'],
      [cut(26), cut(27), 'police'],
      [cut(27), cut(32), 'friday'],
      [cut(32), DUR, 'poll'],
    ],

    /* cues: the picture and the sound read the same numbers */
    vsPop: 0.32,
    ezraGrin: wa('everyone'),
    bookmarkIn: wa('bookmark', at(2)),
    strings: wa('followed', at(3)),
    pins: [wa('three', at(4)), wa('three', at(5)), wa('scenes', at(5))],
    mapLines: wa('all', at(6)),
    mapDisc: wa('one', at(6)),
    shopSign: wa('wren', at(7)),
    bookClose: wa('closed', at(8)),
    ezraSmile: wa('smiled', at(8)),
    ezraLine1: [at(9), end(9)],
    shadowRise: wa('someone', at(10)),
    shadowEyes: wa('darkness', at(10)),
    lean: wa('leaned', at(11)),
    relax: wa('relax', at(11)),
    whisper: [wa('relax', at(11)), end(12)],
    people1: wa('people', at(12)),
    signFlip: wa('closing', at(13)),
    caseGlint: wa('prepared', at(14)),
    justInCase: at(15),
    boxPush: cut(16) + 0.25,
    receiptsFly: wa('receipts', at(16)),
    receiptPops: [at(17), wa('buys', at(17)), wa('book', at(17))],
    fridayMark: wa('friday', at(17)),
    ezraLine2: [at(18), end(18)],
    faces: wa('every', at(18)),
    teamUp: wa('teamed', at(19)),
    blood: wa('blood', at(20)),
    ezraIn: at(21),
    bubble: wa('people', at(21)),
    trapCircle: wa('trap', at(22)),
    bookOut: wa('book', at(23)),
    shelfMark: wa('shelf', at(24)),
    reach: wa('reached', at(25)),
    grip: wa('it', at(25)),
    grab: wa('got', at(25)),
    stamp: wa('caught', at(25)),
    questions: [at(26) + 0.05, wa('never', at(26)), wa('solved', at(26))],
    calDrop: wa('friday', at(28)),
    calFlips: [wa('same', at(30)), wa('same', at(31))],
    pollSilas: wa('silas', at(32)),
    pollEzra: wa('ezra', at(32)),
    comment: +(end(32) + 0.2).toFixed(3),
  };

  /* captions: ONE word at a time, like the reference. A word stays up until the
     next one starts; after a long pause it clears. Then the end-card line. */
  TL.captions = [];
  WORDS.forEach((w, i) => {
    TL.captions.push([w[0], w[2].replace(/["“”]/g, '')]);
    const next = i + 1 < WORDS.length ? WORDS[i + 1][0] : TL.comment;
    if (next - w[1] > 0.75) TL.captions.push([+(w[1] + 0.35).toFixed(3), '']);
  });
  TL.captions.push([TL.comment, 'Comment below']);
  TL.captions.sort((x, y) => x[0] - y[0]);

  /* lip flaps: how open a mouth is at t while the narrator voices a line in [a, b] */
  TL.mouth = function (t, a, b) {
    if (t < a || t > b) return 0;
    for (const w of WORDS) {
      if (w[0] > b) break;
      if (t >= w[0] && t <= w[1]) { const p = (t - w[0]) * 11; return 0.25 + 0.75 * Math.abs(Math.sin(p + w[0] * 3)); }
    }
    return 0;
  };

  TL.chapters = [
    [0, cut(1), 'What if…'], [cut(1), cut(7), 'The bookmarks'], [cut(7), cut(13), 'Wren & Page'],
    [cut(13), cut(19), 'After closing'], [cut(19), cut(26), 'The trap'], [cut(26), DUR, 'Every Friday'],
  ];

  TL.shotAt = function (t) { for (const s of TL.shots) if (t >= s[0] && t < s[1]) return s; return TL.shots[TL.shots.length - 1]; };
  TL.captionAt = function (t) { let c = null; for (const k of TL.captions) { if (k[0] <= t) c = k; else break; } return c && c[1] ? c : null; };
  TL.at = at; TL.end = end; TL.wa = wa;

  g.TL = TL;
})(window);
