"""Room 9: narration + ElevenLabs SFX on the film's timeline -> films/motel/audio/voice_sfx.wav/.mp3
and films/motel/voice-data.js (narrator segments, so the score ducks). Cue times mirror films/motel/core.js.
usage: python3 films/motel/mix.py
"""
import json, subprocess, wave
import numpy as np

SR, DUR = 44100, 77.6
B = 'films/motel/audio/'
S = json.load(open(B + 'narration.timings.json'))['sentences']
at = lambda i: S[i][0]

def load(path, af=None):
    cmd = ['ffmpeg', '-v', 'error', '-i', path] + (['-af', af] if af else []) + ['-ac', '1', '-ar', str(SR), '-f', 'f32le', '-']
    return np.frombuffer(subprocess.run(cmd, capture_output=True, check=True).stdout, dtype=np.float32).copy()
def norm(x, peak_db):
    p = np.abs(x).max(); return x if p < 1e-6 else x * (10 ** (peak_db / 20) / p)
sfx = np.zeros(int((DUR + 20) * SR), dtype=np.float32)
def place(x, t, gain_db=0.0, length=None, fade_in=0.0, fade_out=0.08):
    if length: x = x[:int(length * SR)].copy()
    fi, fo = min(len(x) // 2, int(fade_in * SR)), min(len(x) // 2, int(fade_out * SR))
    if fi: x[:fi] *= np.linspace(0, 1, fi)
    if fo: x[-fo:] *= np.linspace(1, 0, fo)
    s = int(t * SR); sfx[s:s + len(x)] += x * 10 ** (gain_db / 20)
D = B + 'sfx/'

# night ambience bed (neon buzz + crickets) under the exterior/early shots: chain the two takes
amb = [norm(load(D + 'amb_1.mp3'), -14), norm(load(D + 'amb_2.mp3'), -14)]
t, i = at(3) - 0.3, 0
while t < at(10) + 3:
    w = amb[i % 2].copy(); f = int(0.3 * SR); w[:f] *= np.linspace(0, 1, f); w[-f:] *= np.linspace(1, 0, f)
    place(w, t, -6 if at(4) <= t < at(10) else 0); t += len(w) / SR - 0.3; i += 1
# TV static in the room
tv = norm(load(D + 'tv_2.mp3', 'highpass=f=400'), -10)
for t0, t1, g in [(at(4), at(6), -14), (at(7), at(8), -4), (at(9), at(10), -14), (at(13), TL_tvoff := at(18) + 0.15, -16)]:
    t = t0
    while t < t1:
        place(tv, t, g, length=min(2.0, t1 - t), fade_in=0.05, fade_out=0.05); t += 1.95
place(norm(load(D + 'tvoff_1.mp3'), -4), at(18) + 0.1)
# across the lot: the struggle, distant
place(norm(load(D + 'struggle_2.mp3', 'lowpass=f=2500'), -8), at(12) + 0.25)
place(norm(load(D + 'struggle_1.mp3', 'lowpass=f=2000'), -12), at(12) + 0.6)
# remote cracks on the tiles
place(norm(load(D + 'remote_1.mp3', 'highpass=f=200'), -4), at(15) + 0.02)
place(norm(load(D + 'cornrun_2.mp3', 'highpass=f=1500'), -16), at(15) + 0.05)  # little skitter of batteries
# lamp click (reuse the TV-off click tail)
place(norm(load(D + 'tvoff_1.mp3', 'highpass=f=1500'), -8), at(19) + 1.2, length=0.25)
# the handles along the row, then OUR handle
hd = [norm(load(D + 'handle_1.mp3'), -6), norm(load(D + 'handle_2.mp3'), -4)]
for k, tc in enumerate([at(22) - 0.2, at(23) - 0.2, at(24) - 0.2]): place(hd[0], tc, -10 + k * 2, length=0.9)
place(hd[1], at(25), 0)
place(hd[0], at(27) + 0.02, 0, length=0.6)
# the key
place(norm(load(D + 'key_1.mp3'), -4), at(28) + 0.0)
place(norm(load(D + 'key_2.mp3'), -6), at(28) + 0.45)
# the bathroom window + squeezing through
place(norm(load(D + 'window_1.mp3'), -4), at(33) + 0.4)
place(norm(load(D + 'window_2.mp3'), -6), at(34) + 0.4)
# running through the corn (16 s take)
place(norm(load(D + 'cornrun_1.mp3'), -3), at(35) + 0.6, length=at(38) - at(35) + 0.2, fade_in=0.4, fade_out=0.6)
place(norm(load(D + 'cornrun_1.mp3'), -3)[int(8 * SR):], at(39), -6, length=3.0, fade_in=0.5, fade_out=0.5)
# the motel door kicked open, far behind
place(norm(load(D + 'doorkick_1.mp3', 'lowpass=f=3000,aecho=0.7:0.5:90:0.3'), -2), at(38) + 1.5)
# the final crash through the corn into the reveal
place(norm(load(D + 'final_1.mp3'), -1), 75.15 - 1.2)
place(norm(load(D + 'final_2.mp3'), -4), 75.15)

voice = load(B + 'narration.wav', 'highpass=f=70,equalizer=f=3000:t=q:w=1.2:g=2.5,acompressor=threshold=-30dB:ratio=6:attack=4:release=120:makeup=14dB,alimiter=limit=0.89:level=false')
out = sfx[:int(DUR * SR)] * 0.8
out[:min(len(voice), len(out))] += voice[:len(out)]
peak = np.abs(out).max()
if peak > 0.97: out *= 0.97 / peak
with wave.open(B + 'voice_sfx.wav', 'wb') as w:
    w.setnchannels(1); w.setsampwidth(2); w.setframerate(SR); w.writeframes((out * 32767).astype(np.int16).tobytes())
subprocess.run(['ffmpeg', '-v', 'error', '-y', '-i', B + 'voice_sfx.wav', '-b:a', '160k', B + 'voice_sfx.mp3'], check=True)
segs = [[round(a, 2), round(b, 2)] for a, b, _ in S]
merged = []
for a, b in segs:
    if merged and a - merged[-1][1] < 0.35: merged[-1][1] = b
    else: merged.append([a, b])
open('films/motel/voice-data.js', 'w').write('/* generated by films/motel/mix.py */\nwindow.VOICE = { file: "films/motel/audio/voice_sfx.mp3", wav: "films/motel/audio/voice_sfx.wav", segments: ' + json.dumps(merged) + ' };\n')
print('ok, peak', round(float(peak), 3), 'segments', len(merged))
