"""Black hole: put the narration on the film timeline.

The take is used at its natural pace. Everything up to "Nothing could survive out here." starts at OFFSET;
a held breath of GAP seconds is opened before the whispered "Nothing human." (the creature steps out in it),
and the whispered "Wait." is cut out of the take and moved to WAIT_AT, after the cut to black.
The per-word times from the ElevenLabs transcript are moved the same way.

Writes films/blackhole/words.js, films/blackhole/audio/voice.wav/.mp3 and films/blackhole/voice-data.js.
usage: python3 films/blackhole/prep_narration.py
"""
import json, re, subprocess, wave
import numpy as np

SR = 44100
B = 'films/blackhole/'
SRC = B + 'audio/raw/narr_a.mp3'
WORDS = json.load(open(B + 'audio/raw/narr_a.words.json'))['words']
OFFSET = 0.4      # the first word starts here
HOLD = 70.65      # in the take: inside the pause after "...out here."
GAP = 1.3         # extra silence opened there
SPLIT = 72.25     # in the take: inside the pause before the whispered "Wait."
WAIT_AT = 76.0    # film time for "Wait."
DUR = 86.0        # the film, end cards included

pcm = subprocess.run(['ffmpeg', '-v', 'error', '-i', SRC, '-ac', '1', '-ar', str(SR), '-f', 'f32le', '-'], capture_output=True, check=True).stdout
x = np.frombuffer(pcm, dtype=np.float32).copy()
words = [w for w in WORDS if w['type'] == 'word' and not w['text'].startswith('[')]

# where "Wait." starts in the take (first sound after SPLIT)
log = subprocess.run(['ffmpeg', '-hide_banner', '-i', SRC, '-af', 'silencedetect=noise=-45dB:d=0.1', '-f', 'null', '-'], capture_output=True, text=True).stderr
ends = [float(v) for v in re.findall(r'silence_end: ([\d.]+)', log)]
wait_src = min(e for e in ends if e > SPLIT) - 0.03
# the transcript's word times drift late at the very end of the take: words that run past a cut point
# are clamped to where the audio actually falls silent before it
starts = [float(v) for v in re.findall(r'silence_start: ([\d.]+)', log)]
for cut in (HOLD, SPLIT):
    quiet = max(s for s in starts if s < cut)
    for w in words:
        if w['start'] < cut < w['end'] + 0.3:
            w['end'] = quiet; w['start'] = min(w['start'], quiet - 0.4)

def place(t):
    if t < HOLD: return round(OFFSET + t, 3)
    if t < SPLIT: return round(OFFSET + GAP + t, 3)
    return round(WAIT_AT + (t - wait_src), 3)

film = np.zeros(int(DUR * SR), dtype=np.float32)
f = int(0.02 * SR)
def put(seg, at, fade_in=True, fade_out=True):
    seg = seg.copy()
    if fade_in: seg[:f] *= np.linspace(0, 1, f)
    if fade_out: seg[-f:] *= np.linspace(1, 0, f)
    s = int(at * SR); film[s:s + len(seg)] += seg[:len(film) - s]
put(x[:int(HOLD * SR)], OFFSET, fade_in=False)
put(x[int(HOLD * SR):int(SPLIT * SR)], OFFSET + GAP + HOLD)
put(x[int(wait_src * SR):], WAIT_AT, fade_out=False)
film /= max(1e-6, np.abs(film).max()) / 0.89
with wave.open(B + 'audio/narration.wav', 'wb') as w:
    w.setnchannels(1); w.setsampwidth(2); w.setframerate(SR)
    w.writeframes((np.clip(film, -1, 1) * 32767).astype(np.int16).tobytes())

wl = [[place(w['start']), place(w['end']), w['text']] for w in words]
sents, cur = [], []
for w in wl:
    cur.append(w)
    if w[2].endswith(('.', '?', '!')) and not w[2].endswith('...'):
        sents.append([cur[0][0], cur[-1][1], ' '.join(v[2] for v in cur)]); cur = []
if cur: sents.append([cur[0][0], cur[-1][1], ' '.join(v[2] for v in cur)])

open(B + 'words.js', 'w').write(
    '/* generated by films/blackhole/prep_narration.py: narration timing on the film timeline */\n'
    f'window.BH_DURATION = {DUR};\n'
    'window.BH_WORDS = ' + json.dumps(wl) + ';\n'
    'window.BH_SENTENCES = ' + json.dumps(sents, indent=0) + ';\n')
json.dump({'duration': DUR, 'words': wl, 'sentences': sents}, open(B + 'audio/narration.timings.json', 'w'), indent=1)

# the voice track: low-end kept (it's a deep voice), a little presence, gentle compression, -16 LUFS
subprocess.run(['ffmpeg', '-v', 'error', '-y', '-i', B + 'audio/narration.wav', '-af',
                'highpass=f=45,equalizer=f=2800:t=q:w=1.2:g=2,acompressor=threshold=-26dB:ratio=3:attack=5:release=150:makeup=6dB,loudnorm=I=-16:TP=-2:LRA=9,alimiter=limit=0.89:level=false',
                B + 'audio/voice.wav'], check=True)
subprocess.run(['ffmpeg', '-v', 'error', '-y', '-i', B + 'audio/voice.wav', '-b:a', '160k', B + 'audio/voice.mp3'], check=True)
merged = []
for a, b, _ in sents:
    if merged and a - merged[-1][1] < 0.35: merged[-1][1] = b
    else: merged.append([a, b])
open(B + 'voice-data.js', 'w').write('/* generated by films/blackhole/prep_narration.py */\nwindow.VOICE = { file: "films/blackhole/audio/voice.mp3", wav: "films/blackhole/audio/voice.wav", segments: '
                                     + json.dumps([[round(a, 2), round(b, 2)] for a, b in merged]) + ' };\n')
for i, s in enumerate(sents): print(f'{i:2d} {s[0]:6.2f}-{s[1]:6.2f}  {s[2]}')
print(f'"Wait." moved from {wait_src:.2f} to {WAIT_AT}; film {DUR}s; {len(wl)} words')
