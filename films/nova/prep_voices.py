"""Betelgeuse (POV): cut the two voice takes into lines and place each line on the film timeline.

The friend (ElevenLabs premade "Brian"; white captions) and the hero (the POV, "Lip"; #FFD54A captions) were generated
as one take each (friend take A, checked word for word with Scribe). Each take is split at its pauses; pieces that
belong to one line are joined (with their original pause, or a set gap), and every line is set where its scene plays.
The story runs by the fire, at the window, out into the snow, to the explosion at the end; three lines of the takes
are not used ("Where's that light coming from?", the half Moon, Orion losing its shoulder).

Writes films/nova/lines.js, films/nova/audio/narration.wav and films/nova/audio/voice.wav.
usage: python3 films/nova/prep_voices.py
"""
import json, subprocess, wave
import numpy as np

SR = 44100
B = 'films/nova/'
DUR = 59.0
FRIEND = [  # (start, caption, pieces of the take that make the line, gap between pieces or None for the take's own)
    (0.06, 'A star just exploded. Right there.', [0, 1], 0.0),                       # the hook: a flash-forward to 37.2
    (7.7, "That's Betelgeuse. The red star on Orion's shoulder.", [3, 4], None),
    (11.6, "It's so big that if it replaced our Sun, it would swallow Mars.", [5], None),
    (16.1, 'Hours ago, its neutrinos flew straight through the Earth.', [8], None),
    (20.95, 'Through us. Billions of billions of them.', [9, 10], None),
    (25.9, "No. It's over five hundred light-years away.", [6, 7], None),
    (37.2, 'A star just exploded. Right there.', [0, 1], 0.0),                       # outside: the moment the hook showed
    (40.5, 'In five seconds, light from an exploding star reaches Earth.', [2], None),
    (47.0, 'Look at the snow. One star is casting shadows.', [11, 12], None),
    (54.5, 'It could happen tonight. Or in a hundred thousand years.', [17, 18], None),
]
HERO = [  # (start, caption, pieces, loudness dBFS RMS)
    (19.55, 'Through us?', [2], -22),
    (24.45, 'Can it hurt us?', [1], -21),
    (50.6, 'So everyone after us gets a different sky.', [3], -22),
]

def load(path):
    return np.frombuffer(subprocess.run(['ffmpeg', '-v', 'error', '-i', path, '-ac', '1', '-ar', str(SR), '-f', 'f32le', '-'],
                                        capture_output=True, check=True).stdout, dtype=np.float32).copy()
def split(x, thr_db, min_gap=0.28, min_len=0.15):
    w = int(0.02 * SR); e = np.array([np.sqrt(np.mean(x[i:i + w] ** 2)) for i in range(0, len(x) - w, w)])
    on = 20 * np.log10(e + 1e-9) > thr_db; out, i, n = [], 0, len(on)
    while i < n:
        if not on[i]: i += 1; continue
        j = i
        while j < n:
            if on[j]: j += 1; continue
            k = j
            while k < n and not on[k]: k += 1
            if k - j >= min_gap / 0.02 or k == n: break
            j = k
        if (j - i) * 0.02 > min_len: out.append([max(0, i * 0.02 - 0.06), min(len(x) / SR, j * 0.02 + 0.12)])
        i = j
    return out

friend, hero = load(B + 'audio/raw/friend_a.mp3'), load(B + 'audio/raw/hero_a.mp3')
fs, hs = split(friend, -42), split(hero, -46)
assert len(fs) == 19 and len(hs) == 4, (len(fs), len(hs))
film = np.zeros(int(DUR * SR), dtype=np.float32)
rms = lambda a: np.sqrt(np.mean(a ** 2)) + 1e-9
def put(seg, t, gain):
    seg = seg.copy(); f = int(0.015 * SR); seg[:f] *= np.linspace(0, 1, f); seg[-f:] *= np.linspace(1, 0, f)
    s = int(t * SR); film[s:s + len(seg)] += seg[:len(film) - s] * gain
lines = []
fg = 10 ** (-19 / 20) / rms(np.concatenate([friend[int(a * SR):int(b * SR)] for a, b in fs]))
for t, text, ps, gap in FRIEND:
    if gap is None:
        a, b = fs[ps[0]][0], fs[ps[-1]][1]; put(friend[int(a * SR):int(b * SR)], t, fg); end = t + b - a
    else:
        tt = t
        for p in ps:
            a, b = fs[p]; put(friend[int(a * SR):int(b * SR)], tt, fg); end = tt + b - a; tt = end + gap
    lines.append([round(t, 3), round(end, 3), 'friend', text])
for t, text, ps, db in HERO:
    a, b = hs[ps[0]][0], hs[ps[-1]][1]; seg = hero[int(a * SR):int(b * SR)]; put(seg, t, 10 ** (db / 20) / rms(seg)); lines.append([round(t, 3), round(t + b - a, 3), 'hero', text])
lines.sort()
for i in range(len(lines) - 1): assert lines[i][1] < lines[i + 1][0] + 0.05, lines[i:i + 2]
film = np.clip(film, -0.98, 0.98)
with wave.open(B + 'audio/narration.wav', 'wb') as w:
    w.setnchannels(1); w.setsampwidth(2); w.setframerate(SR); w.writeframes((film * 32767).astype(np.int16).tobytes())
subprocess.run(['ffmpeg', '-v', 'error', '-y', '-i', B + 'audio/narration.wav', '-af',
                'highpass=f=55,equalizer=f=3000:t=q:w=1.2:g=1.5,acompressor=threshold=-24dB:ratio=2.5:attack=5:release=150:makeup=3dB,alimiter=limit=0.89:level=false',
                B + 'audio/voice.wav'], check=True)
open(B + 'lines.js', 'w').write('/* generated by films/nova/prep_voices.py: [start, end, voice, caption] */\n'
                                f'window.NV_DURATION = {DUR};\nwindow.NV_LINES = ' + json.dumps(lines, indent=0, ensure_ascii=False) + ';\n')
for l in lines: print(f'{l[0]:6.2f}-{l[1]:6.2f} {l[2]:6s} {l[3]}')
